local function senderKey(name)
    return WoWStatusPopups and WoWStatusPopups.senderKey(name)
end
local function playerClass(item)
    -- Armor class_id is an item category, NEVER the player's class.
    local wanted = senderKey(item.sender)
    if not wanted then return nil end
    local units = {"player", "target", "focus", "mouseover"}
    for i=1,4 do units[#units+1]="party"..i end
    for i=1,40 do units[#units+1]="raid"..i end
    for _,unit in ipairs(units) do
        local name,realm = S.call(UnitName,unit)
        name,realm = S.string(name),S.string(realm)
        if name then
            realm=realm or S.stringCall(WoWStatusAdapter.realmName)
            local full=name:find("-",1,true) and name or (realm and name.."-"..realm:gsub("%s","") or nil)
            if full and senderKey(full)==wanted then
                local _,token=S.call(UnitClass,unit)
                token=S.string(token)
                if token and banks.death then return token end
            end
        end
    end
end
local function category(item)
    if item.level then return "level" end
    if item.kind=="profession" and (item.text or ""):match("^Learned ") then return "profession_learned" end
    return item.kind
end
local function choices(item,kind)
    if kind~="death" then return banks[kind] end
    local class=playerClass(item)
    local pool={}
    for _,line in ipairs(banks.death) do
        local tag,copy=line:match("^%[([A-Z]+)%] (.+)$")
        if tag=="ANY" or tag==class then pool[#pool+1]=copy end
    end
    return pool
end
local previous={}
function F.text(item)
    if type(item)~="table" then return "" end
    if item.flavour then return item.flavour end
    local kind=category(item)
    local pool=choices(item,kind)
    if not pool or #pool==0 then return "" end
    local seed=item.id
    if not seed and item.nonce then
        local key=senderKey(item.sender)
        if key then seed=WoWStatusAdapter.client_id..":"..key..":"..item.nonce end
    end
    local index
    if seed and not item.preview then
        -- Event identity gives peers the same draw from the same available pool.
        -- Safe integer arithmetic in Lua 5.1; no global RNG reseeding.
        local hash=5381
        for i=1,#seed do hash=(hash*131+seed:byte(i))%4294967291 end
        index=hash%#pool+1
    else
        index=math.random(#pool)
        if #pool>1 and previous[kind]==pool[index] then index=index%#pool+1 end
        previous[kind]=pool[index]
    end
    item.flavour=pool[index]
    return item.flavour
end
